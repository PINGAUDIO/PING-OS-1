"""PING FM1's sound logo: the studio's recording, compressed into the firmware (app/sound_logo.h).
    python tools/make_sound_logo.py [WAV]      (default assets/ping_sound_logo.wav: 16-bit stereo, any rate)
Trims to LENGTH seconds with a short fade, peaks it at PEAK, resamples to RATE (a windowed-sinc low-pass,
then interpolation) and encodes each channel in the engine's blocked IMA ADPCM (engine/ch_adpcm.c: the
same greedy encoder, 64 frames a block, 4-byte headers), so app/ping_logo.h decodes it straight out of
flash. Standard library only."""
import array, math, os, sys, wave

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'assets', 'ping_sound_logo.wav')
RATE, LENGTH, FADE, PEAK = 32000, 4.4, 0.25, 0.85   # (the recording is silent from 4.38 s)
BLOCK = 64

w = wave.open(SRC)
sr, ch, sw = w.getframerate(), w.getnchannels(), w.getsampwidth()
assert sw == 2, 'needs 16-bit PCM'
raw = array.array('h', w.readframes(w.getnframes()))
chans = [[raw[i * ch + c] / 32768.0 for i in range(len(raw) // ch)] for c in range(ch)]
if ch == 1: chans = [chans[0], chans[0]]
chans = chans[:2]

n_in = min(len(chans[0]), int(LENGTH * sr))
for c in chans:
    del c[n_in:]
    nf = int(FADE * sr)
    for i in range(nf): c[n_in - nf + i] *= 0.5 + 0.5 * math.cos(math.pi * i / nf)
# mono: the two channels summed (the firmware's flash is short: one channel is half the bytes). The loss is printed:
# the sum's level against the channels' own, 0 dB when they are alike, lower the wider the recording
e_st = sum(v * v for c in chans for v in c) / 2
mono = [(a + b) * 0.5 for a, b in zip(chans[0], chans[1])]
e_mo = sum(v * v for v in mono)
print('mono sum: %.1f dB against the stereo channels' % (10 * math.log10(e_mo / e_st) if e_st > 0 and e_mo > 0 else 0))
chans = [mono]
pk = max(max(abs(v) for v in c) for c in chans)
for c in chans:
    for i in range(len(c)): c[i] *= PEAK / pk

# resample: output sample k at input position k * sr / RATE, a 32-tap Hann-windowed sinc cut at 0.45 RATE
ratio = sr / RATE
fc = 0.45 * RATE / sr                           # cutoff, cycles per input sample
TAPS = 32
def resample(x):
    n_out = int(len(x) / ratio)
    y = [0.0] * n_out
    for k in range(n_out):
        p = k * ratio; i0 = int(p) - TAPS // 2 + 1
        acc = 0.0
        for j in range(i0, i0 + TAPS):
            if 0 <= j < len(x):
                t = j - p
                win = 0.5 + 0.5 * math.cos(math.pi * t / (TAPS / 2))
                s = 2 * fc if t == 0 else math.sin(2 * math.pi * fc * t) / (math.pi * t)
                acc += x[j] * s * win
        y[k] = acc
    return y

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
        107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796,
        876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871,
        5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623,
        27086, 29794, 32767]
IDX = [-1, -1, -1, -1, 2, 4, 6, 8, -1, -1, -1, -1, 2, 4, 6, 8]
def dec(code, p, ix):
    step = STEP[ix]; d = step >> 3
    if code & 4: d += step
    if code & 2: d += step >> 1
    if code & 1: d += step >> 2
    p = p - d if code & 8 else p + d
    p = max(-32768, min(32767, p))
    ix = max(0, min(88, ix + IDX[code]))
    return p, ix
def encode(pcm):
    out = bytearray(); index = 0
    for start in range(0, len(pcm), BLOCK):
        pred = pcm[start]
        b = bytearray(4 + BLOCK // 2)
        b[0] = pred & 255; b[1] = (pred >> 8) & 255; b[2] = index; b[3] = 0
        for i in range(BLOCK):
            target = pcm[start + i] if start + i < len(pcm) else 0
            best = None
            for code in range(16):
                p, ix = dec(code, pred, index)
                e = abs(p - target)
                if best is None or e < best[0]: best = (e, code, p, ix)
            _, code, pred, index = best
            if i & 1: b[4 + i // 2] |= code << 4
            else: b[4 + i // 2] = code
        out += b
    return out, index

encoded = []
for c in chans:
    y = resample(c)
    pcm = [max(-32768, min(32767, int(round(v * 32767)))) for v in y]
    data, _ = encode(pcm)
    encoded.append((len(pcm), data))
frames = min(e[0] for e in encoded)

out = os.path.join(ROOT, 'app', 'sound_logo.h')
with open(out, 'w', encoding='ascii') as f:
    f.write('/* generated by tools/make_sound_logo.py from %s: the PING sound logo, blocked IMA ADPCM\n'
            ' * (engine/ch_adpcm.h), mono, %d Hz */\n' % (os.path.basename(SRC), RATE))
    f.write('#define SLOGO_RATE %d\n#define SLOGO_FRAMES %du\n' % (RATE, frames))
    for name, (_, data) in zip(('slogo',), encoded):
        f.write('static const uint8_t %s[%d] = {\n' % (name, len(data)))
        for k in range(0, len(data), 24):
            f.write('    ' + ','.join(str(v) for v in data[k:k + 24]) + ',\n')
        f.write('};\n')
print('wrote %s: %d frames at %d Hz (%.2f s), %d bytes' % (out, frames, RATE, frames / RATE, sum(len(e[1]) for e in encoded)))
