# Generates engine/ch_mi_tables.c: the lookup tables PING OS-1's Mutable Instruments ports need, computed from the
# formulas in Plaits' plaits/resources/lookup_tables.py (Emilie Gillet, MIT; see docs/THIRD_PARTY.md).
# Plain Python (no numpy). Run: python tools/gen_mi_tables.py
import math, os

out = []
def emit_i16(name, vals, per=12):
    out.append('const int16_t %s[%d] = {' % (name, len(vals)))
    for i in range(0, len(vals), per):
        out.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    out.append('};')
def emit_f(name, vals, per=8):
    out.append('const float %s[%d] = {' % (name, len(vals)))
    for i in range(0, len(vals), per):
        out.append('    ' + ', '.join(('%.8ef' % v) for v in vals[i:i + per]) + ',')
    out.append('};')

# ---- the waveshapers (Plaits: "stolen from Tides"), 257 points each, -1..1 in Q15 ----
N = 128
x = [i / float(N) for i in range(N + 1)]
tan_ = [math.atan(8 * math.cos(math.pi * v)) for v in x]
scale = max(tan_)
fade = [min(1.0, 4.0 - 4.0 * v) for v in x]
linear = x[:]
bump = [(1.0 - math.cos(math.pi * v * 1.5)) * (1.0 - math.cos(math.pi * f)) / 4.5 for v, f in zip(x, fade)]
double_bump = [math.sin(math.pi * v * 1.5) for v in x]
inverse_sin = [math.acos(1 - 2 * v) / math.pi for v in x]
inverse_tan = [math.acos(math.tan(scale * (1.0 - 2.0 * v)) / 8.0) / math.pi for v in x]
def flip(t):
    full = [-v for v in t[N:0:-1]] + t
    return [int(round(v * 32767.0)) for v in full]
ws = [flip(inverse_tan), flip(inverse_sin), flip(linear), flip(bump), flip(double_bump)]
out.append('/* the five waveshapers FOLD blends between (SHAPE): inverse tan, inverse sine, linear, bump, double bump */')
flat = []
for t in ws: flat += t
emit_i16('ch_mi_ws', flat)

# ---- the wavefolders: 516 points over -1..1 (Hermite-read from [1]), as Q15 ----
M = 512
xs = [i / (M / 2.0) - 1.0 for i in range(M + 4)]
xs[-1] = xs[-2]
fold = []
for v in xs:
    w = math.exp(-v * v * 4) ** 2
    fold.append(math.sin(8 * math.pi * v) * w + math.atan(3 * v) * (1 - w))
m = max(abs(v) for v in fold)
fold = [v / m for v in fold]
def deadband(vin, r_in, r_load, r_fb=150.0e3, v_sat=10.47):
    vo = -r_fb / r_in * vin
    vo = min(max(vo, -v_sat), v_sat) if vo < v_sat else v_sat
    return (vin * r_fb * r_load + vo * r_in * r_load) / (r_fb * r_load + r_in * r_load + r_in * r_fb)
def diode(v): return 0.7 * v / (0.3 + abs(v))
fold2 = []
for v in xs:
    vin = v * 12.0
    s1 = deadband(vin, 10e3, 100e3); s2 = deadband(vin, 49.9e3, 44.2e3); s3 = deadband(vin, 91e3, 18e3)
    s4 = deadband(vin, 30e3, 71.4e3); s5 = deadband(vin, 68e3, 33.0e3)
    s45 = -33.0 / 71.4 * s4 - 33.0 / 33.0 * s5 - 33.0 / 240.0 * vin
    fold2.append(diode(-150.0 / 100.0 * s1 - 150.0 / 44.2 * s2 - 150.0 / 18.0 * s3 - 150.0 / 33.0 * s45))
m2 = max(fold2)
fold2 = [v / m2 for v in fold2]
out.append('/* the wavefolders: a sine folder fading into an arctan (FOLD), and a model of an analogue folder (its overtone path) */')
emit_i16('ch_mi_fold', [int(round(max(-1, min(1, v)) * 32767)) for v in fold])
emit_i16('ch_mi_fold2', [int(round(max(-1, min(1, v)) * 32767)) for v in fold2])

# ---- stiffness: the partials' stretch for the modal resonator (65 points) ----
st = []
for i in range(65):
    g = i / 64.0
    if g < 0.25: s = -(0.25 - g) * 0.25
    elif g < 0.3: s = 0.0
    elif g < 0.9: s = 0.01 * 10 ** (((g - 0.3) / 0.6) * 2.005) - 0.01
    else:
        gg = ((g - 0.9) / 0.1) ** 2
        s = 1.5 - math.cos(gg * math.pi) / 2.0
    st.append(s)
st[-1] = 2.0; st[-2] = 2.0
out.append('/* the stiffness curve: how far each partial is stretched from harmonic (MODAL) */')
emit_f('ch_mi_stiffness', st)

head = ['/* SPDX-License-Identifier: MIT',
        ' * Lookup tables for PING OS-1\'s ports of Mutable Instruments code, computed from the formulas of Plaits\'',
        ' * plaits/resources/lookup_tables.py (Copyright 2016 Emilie Gillet, MIT; see docs/THIRD_PARTY.md).',
        ' * Generated by tools/gen_mi_tables.py: do not edit by hand. */',
        '#include <stdint.h>', '']
path = os.path.join(os.path.dirname(__file__), '..', 'engine', 'ch_mi_tables.c')
open(path, 'w', newline='\n').write('\n'.join(head + out) + '\n')
print('wrote', os.path.normpath(path))
