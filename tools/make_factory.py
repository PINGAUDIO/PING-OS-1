"""The factory project, from a project file saved by the page's Transfer tab (a .pingos): writes app/factory.h,
the project's store objects packed small, which the firmware unpacks into its store the first time it is switched on
(app.c factory_seed).
    python tools/make_factory.py FILE.pingos [--no-presets] [--pattern-1]     (--pattern-1: pattern 1 alone, the others left out)
The sample bank in the file is left out: the firmware ships with an empty bank, so a factory project must not play
samples (this stops if a track's engine is SAMPLE or GRAIN).

The packing, an object at a time (the firmware unpacks into its one 3840-byte buffer):
    obj u8, packed length u16, then tokens until the packed length is used up:
        0x00..0x7F  n: n + 1 bytes follow, copied as they are
        0x80..0xFF  n, then d u8: (n & 0x7F) + 3 bytes copied from d + 1 bytes back (d 0: the last byte again, a run)
    and after the last object: 0xFF.
An object's zeros at its end are not stored: the buffer is cleared first and the object's own header has its length."""
import struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = ['SETTINGS', 'PROJECT', 'PANEL', 'TRK0', 'TRK1', 'TRK2', 'TRK3', 'PRE0', 'PRE1', 'PRE2', 'PRE3'] + [f'PT{k}' for k in range(16)]
DEV_POLY, DEV_GRAIN = 2, 5                                # (engine/chisel.h: the SAMPLE and GRAIN engines' numbers)

def pack(d):
    out, lit, i, n = bytearray(), bytearray(), 0, len(d)
    def flush():
        nonlocal lit
        while lit:
            c = lit[:128]; out.append(len(c) - 1); out.extend(c); lit = lit[128:]
    while i < n:
        best, bd = 0, 0
        for dist in range(1, min(i, 256) + 1):
            m = 0
            while m < 130 and i + m < n and d[i + m] == d[i + m - dist]: m += 1
            if m > best: best, bd = m, dist
        if best >= 3:
            flush(); out.append(0x80 | (best - 3)); out.append(bd - 1); i += best
        else:
            lit.append(d[i]); i += 1
    flush()
    return bytes(out)

def unpack(p, size):
    out, i = bytearray(), 0
    while i < len(p):
        t = p[i]; i += 1
        if t < 0x80: out += p[i:i + t + 1]; i += t + 1
        else:
            d = p[i] + 1; i += 1
            for _ in range((t & 0x7F) + 3): out.append(out[-d])
    return bytes(out) + bytes(size - len(out))

def main():
    src = Path(sys.argv[1]); presets = '--no-presets' not in sys.argv
    b = src.read_bytes()
    if b[:4] != b'PNGP': sys.exit(f'{src}: not a project file')
    i, objs = 8, []
    while b[i] != 0:
        kind = b[i]; id_, ln = struct.unpack_from('<II', b, i + 1); d = b[i + 9:i + 9 + ln]; i += 9 + ln
        if kind != 1: continue                                    # (the sample bank)
        if 3 <= id_ <= 6 and d[8] in (DEV_POLY, DEV_GRAIN): sys.exit(f'{src}: track {id_ - 2} plays samples, and the firmware ships with none')
        if 7 <= id_ <= 10 and not presets: continue
        if id_ > 11 and '--pattern-1' in sys.argv: continue
        objs.append((id_, d))
    blob = bytearray()
    for id_, d in objs:
        p = pack(d.rstrip(b'\0'))
        assert unpack(p, len(d)) == d, NAMES[id_]
        blob += bytes([id_]) + struct.pack('<H', len(p)) + p
        print(f'  {NAMES[id_]:8} {len(d):5} -> {len(p)}')
    blob.append(0xFF)
    L = [f'/* generated by tools/make_factory.py from {src.name}: the factory project, packed (the format is in that file) */',
         '#pragma once', f'static const unsigned char FACTORY[{len(blob)}] = {{']
    for k in range(0, len(blob), 24): L.append('    ' + ','.join(str(x) for x in blob[k:k + 24]) + ',')
    L.append('};')
    (ROOT / 'app' / 'factory.h').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(f'app/factory.h: {len(blob)} bytes, {len(objs)} objects')

if __name__ == '__main__':
    main()
