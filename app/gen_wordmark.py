"""The splash's wordmark fonts: Jost (indestructible type, SIL OFL 1.1; assets/fonts/), a geometric sans in Futura's
spirit, rendered with fm1-base's tools/gen_font.py into ping_font.h as FONT_WORD (the name) and FONT_TAG (the
tagline), capitals and digits only. Run by the build (fm1.toml gen) and by sim/build.ps1:
    python gen_wordmark.py <gen dir>"""
import sys
from pathlib import Path
APP = Path(__file__).resolve().parent
ROOT = APP.parent
sys.path.insert(0, str(ROOT / "base" / "tools"))
# Pillow without libraqm (Windows): font features are dropped (the wordmark needs none)
from PIL import ImageFont, ImageDraw
for _n in ("getbbox", "getmask", "getmask2", "getlength"):
    _o = getattr(ImageFont.FreeTypeFont, _n)
    def _w(self, *a, _o=_o, **k):
        k.pop("features", None)
        return _o(self, *a, **k)
    setattr(ImageFont.FreeTypeFont, _n, _w)
_t = ImageDraw.ImageDraw.text
def _text(self, *a, **k):
    k.pop("features", None)
    return _t(self, *a, **k)
ImageDraw.ImageDraw.text = _text
import gen_font  # noqa: E402
gen_font.FONTDIRS.append(APP / "assets" / "fonts")

FONTS = [("WORD", "Jost[wght].ttf@wght=700", 26, 32, 95), ("TAG", "Jost[wght].ttf@wght=900", 12, 32, 95),
         ("FOOT", "Jost[wght].ttf@wght=700", 7, 32, 126)]   # the tagline black, to tell it apart; the footnote has lower case
TEXT = {"WORD": "PING OS-1", "TAG": "RHYTHM SYNTHESIS ENGINE", "FOOT": "v1.0.2"}


def main(out):
    lines = ["/* generated by app/gen_wordmark.py: the splash's wordmark in Jost (SIL OFL 1.1, assets/fonts/Jost-OFL.txt) */",
             "#pragma once", "#include <stdint.h>", ""]
    for name, ttf, px, first, last in FONTS:
        h, glyphs = gen_font.render(ttf, px, 1, False, first, last)
        if name in ("WORD", "TAG"):   # only the letters it shows: the others empty (the name as wide as the mark would not fit the flash whole)
            used = {ord(c) for c in TEXT[name]}
            glyphs = [g if first + i in used else (g[0], 0, []) for i, g in enumerate(glyphs)]
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536
        lines.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const felucca_font_t FONT_{name} = {{ {h}, {gen_font.PAD}, {first}, {last}, "
                     f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        # the baseline, from the bitmap's top (the same metrics gen_font crops with), so fonts can share one
        fname, _, var = ttf.partition("@")
        f = ImageFont.truetype(str(gen_font.font_path(fname)), px)
        if var:
            axes = dict(kv.split("=") for kv in var.split(","))
            names = [a["name"] if isinstance(a["name"], str) else a["name"].decode() for a in f.get_variation_axes()]
            f.set_variation_by_axes([float(axes.get(n.lower()[:4], axes.get(n, 0)) or a["default"]) for n, a in zip(names, f.get_variation_axes())])
        asc, desc = f.getmetrics()
        top = max(0, f.getbbox("A8|(")[1] - 1)
        lines.append(f"#define FONT_{name}_BASE {asc - top}   /* the baseline, pixels from the glyph's top */")
        lines.append("")
        width = sum(glyphs[ord(c) - first][0] for c in TEXT[name])
        print(f"wordmark {name}: {ttf} {px}px h {h}, {TEXT[name]!r} {width} px wide, {len(data)} B")
    Path(out, "ping_font.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
